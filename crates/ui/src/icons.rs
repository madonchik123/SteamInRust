/// Map a short icon name (used in plugin manifests) to a glyph.
pub fn by_name(name: &str) -> &'static str {
    match name {
        "bell" => BELL,
        "dice" => DICE,
        "chat" => CHAT,
        "star" => STAR,
        "chart" => CHART_BAR,
        "trophy" => TROPHY,
        "fire" => FIRE,
        "clock" => CLOCK,
        "users" => USERS,
        "note" => NOTE,
        "globe" => GLOBE,
        "controller" => CONTROLLER,
        "lightning" => LIGHTNING,
        "gear" => GEAR,
        _ => PUZZLE,
    }
}
